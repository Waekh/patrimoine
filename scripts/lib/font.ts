/** Draws one glyph with its top-left corner at (x, y). */
export function drawGlyph(c: PixelCanvas, char: string, x: number, y: number, color: RGBA): void {
  const rows = GLYPHS[char]?.split(":");
  if (!rows) return;
  rows.forEach((row, dy) => {
    for (let dx = 0; dx < GLYPH_WIDTH; dx += 1) if (row[dx] === "#") c.set(x + dx, y + dy, color);
  });
}

/**
 * The atlas: every character of CHARSET in a fixed grid, so the renderer can
 * frame a glyph from its index alone. Throws when a character has no bitmap,
 * which would otherwise ship as an invisible hole in every sign.
 */
export function buildFontAtlas(color: RGBA): PixelCanvas {
  const missing = [...CHARSET].filter((char) => !(char in GLYPHS));
  if (missing.length > 0)
    throw new Error(`Glyphes manquants dans la police : ${missing.join(" ")}`);
  const { width, height } = atlasSize();
  const canvas = new PixelCanvas(width, height);
  [...CHARSET].forEach((char, index) => {
    const col = index % (width / CELL_WIDTH);
    const row = Math.floor(index / (width / CELL_WIDTH));
    drawGlyph(canvas, char, col * CELL_WIDTH, row * CELL_HEIGHT, color);
  });
  return canvas;
}
